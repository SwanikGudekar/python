# print sum of natural number til 10 using for loop
#means 1+2+3+4....10

num = 10
sum = 0
for i in range(1,num+1):
    sum += i
print("Sum using for loop ",sum)


# same using while loop

n = 10
summ = 0
i = 1
while i<= n:
    summ += i
    i += 1
print("Sum using while loop ",summ)


